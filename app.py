import os
import time
import uuid
from contextlib import closing

import psycopg2
from psycopg2.extras import RealDictCursor
from psycopg2.errors import UniqueViolation
from flask import (
    Flask, jsonify, render_template, request,
    send_from_directory
)
from werkzeug.utils import secure_filename

app = Flask(__name__)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

UPLOAD_FOLDER = os.environ.get(
    "UPLOAD_DIR", os.path.join(BASE_DIR, "uploads")
)

ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".gif"}

os.makedirs(UPLOAD_FOLDER, exist_ok=True)

app.config["UPLOAD_FOLDER"] = UPLOAD_FOLDER
app.config["MAX_CONTENT_LENGTH"] = 5 * 1024 * 1024


def get_db():
    return psycopg2.connect(
        host=os.environ["DB_HOST"],
        port=int(os.environ.get("DB_PORT", "5432")),
        dbname=os.environ.get("DB_NAME", "profiledb"),
        user=os.environ.get("DB_USER", "profileuser"),
        password=os.environ["DB_PASSWORD"],   # fixed
        connect_timeout=5
    )


def init_db(retries=10, delay=3):
    for attempt in range(1, retries + 1):
        try:
            with closing(get_db()) as conn:
                with conn:
                    with conn.cursor() as cursor:
                        cursor.execute("""
                            CREATE TABLE IF NOT EXISTS profiles (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY
                                    PRIMARY KEY,
                                name TEXT NOT NULL,
                                user_id TEXT NOT NULL UNIQUE,
                                country TEXT NOT NULL,
                                photo TEXT,
                                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                            )
                        """)
            return
        except psycopg2.OperationalError:
            if attempt == retries:
                raise
            app.logger.warning(
                "DB not ready (attempt %s/%s), retrying...", attempt, retries
            )
            time.sleep(delay)


init_db()


@app.errorhandler(413)
def too_large(_):
    return jsonify(error="Image is too large (max 5 MB)"), 413


@app.errorhandler(500)
def server_error(_):
    return jsonify(error="Internal server error"), 500


@app.route("/")
def home():
    return render_template("index.html")


def _remove_upload(filename):
    if filename:
        try:
            os.remove(os.path.join(UPLOAD_FOLDER, filename))
        except OSError:
            pass


@app.route("/api/profiles", methods=["POST"])
def create_profile():
    name = request.form.get("name", "").strip()
    user_id = request.form.get("user_id", "").strip()
    country = request.form.get("country", "").strip()
    photo = request.files.get("photo")

    if not name or not user_id or not country:
        return jsonify(error="All fields are required"), 400

    filename = None

    if photo and photo.filename:
        if not photo.mimetype or not photo.mimetype.startswith("image/"):
            return jsonify(error="Please upload an image"), 400

        ext = os.path.splitext(secure_filename(photo.filename))[1].lower()

        if ext not in ALLOWED_EXTENSIONS:
            return jsonify(error="Unsupported image format"), 400

        filename = f"{uuid.uuid4().hex}{ext}"

        try:
            photo.save(os.path.join(UPLOAD_FOLDER, filename))
        except OSError:
            app.logger.exception("Photo upload failed")
            return jsonify(error="Photo upload failed"), 500

    try:
        with closing(get_db()) as conn:
            with conn:
                with conn.cursor() as cursor:
                    cursor.execute(
                        """
                        INSERT INTO profiles (name, user_id, country, photo)
                        VALUES (%s, %s, %s, %s)
                        RETURNING id
                        """,
                        (name, user_id, country, filename)
                    )
                    profile_id = cursor.fetchone()[0]

        return jsonify(message="Profile saved successfully", id=profile_id), 201

    except UniqueViolation:
        _remove_upload(filename)
        return jsonify(error="This ID already exists"), 409

    except psycopg2.Error:
        _remove_upload(filename)
        app.logger.exception("PostgreSQL database error")
        return jsonify(error="Database error, please try again"), 500


@app.route("/api/profiles", methods=["GET"])
def list_profiles():
    try:
        with closing(get_db()) as conn:
            with conn.cursor(cursor_factory=RealDictCursor) as cursor:
                cursor.execute("""
                    SELECT id, name, user_id, country, photo, created_at
                    FROM profiles
                    ORDER BY id DESC
                """)
                rows = cursor.fetchall()
    except psycopg2.Error:
        app.logger.exception("PostgreSQL database error")
        return jsonify(error="Database error, please try again"), 500

    profiles = []
    for row in rows:
        profile = dict(row)
        if profile["photo"]:
            profile["photo"] = "/uploads/" + profile["photo"]
        profiles.append(profile)

    return jsonify(profiles)


@app.route("/uploads/<path:filename>")
def uploaded_photo(filename):
    return send_from_directory(UPLOAD_FOLDER, filename)


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=8000, debug=False)